const khmerTranslationSources = [
  khmerRequestedContentTranslations,
  khmerPublicFallbackTranslations,
  khmerAdminContentTranslations,
  khmerContentTranslations,
]

let khmerTranslationMap: Map<string, string> | null = null

export function normalizeTranslationKey(value: string) {
  return value
    .normalize('NFC')
    .replace(/\u00a0/g, ' ')
    .replace(/[\u2010-\u2015\u2212]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\s+/g, ' ')
    .trim()
}

function getKhmerTranslationMap() {
  if (khmerTranslationMap) return khmerTranslationMap

  khmerTranslationMap = new Map<string, string>()
  khmerTranslationSources.forEach((source) => {
    Object.entries(source).forEach(([key, translated]) => {
      const normalizedKey = normalizeTranslationKey(key)
      if (!normalizedKey || khmerTranslationMap?.has(normalizedKey)) return

      khmerTranslationMap?.set(normalizedKey, translated)
    })
  })

  return khmerTranslationMap
}

export function translateContentText(value: string, locale: SupportedLocale) {
  if (locale !== 'kh') return value

  const key = normalizeTranslationKey(value)
  if (!key) return value

  return getKhmerTranslationMap().get(key) ?? value
}

export function localizeContentValue<T>(value: T, locale: SupportedLocale): T {
  if (locale !== 'kh') return value

  if (typeof value === 'string') {
    return translateContentText(value, locale) as T
  }

  if (Array.isArray(value)) {
    return value.map((item) => localizeContentValue(item, locale)) as T
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [
        key,
        localizeContentValue(item, locale),
      ]),
    ) as T
  }

  return value
}
