export function normalizeTranslationKey(value: string) {
  return value
    .replace(/\u00a0/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

export function translateContentText(value: string, locale: SupportedLocale) {
  if (locale !== 'kh') return value

  const key = normalizeTranslationKey(value)
  if (!key) return value

  return khmerContentTranslations[key] ?? value
}

export function localizeContentValue<T>(value: T, locale: SupportedLocale): T {
  if (locale !== 'kh') return value

  if (typeof value === 'string') {
    return translateContentText(value, locale) as T
  }

  if (Array.isArray(value)) {
    return value.map((item) => localizeContentValue(item, locale)) as T
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [
        key,
        localizeContentValue(item, locale),
      ]),
    ) as T
  }

  return value
}
